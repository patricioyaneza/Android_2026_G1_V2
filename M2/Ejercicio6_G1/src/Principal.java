
public class Principal {

	public static void main(String[] args) {
		int resultado = 2 + 4 * 5;
		System.out.println("El resultado es: " + resultado);
		int resultado2 = 2 + (4 * 5);
		System.out.println("El resultado2 es: " + resultado2);
		int resultado3 = 5 * 4 / 3;
		System.out.println("El resultado3 es: " + resultado3);
		double resultado4 = (double)5 * 4 / 3;
		System.out.println("El resultado4 es: " + resultado4);
		int resultado5 = 5 * (4 + 3);
		System.out.println("El resultado5 es: " + resultado5);

		
	}

}
